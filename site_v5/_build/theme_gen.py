# Run from the repo root:  python site_v5/_build/theme_gen.py   (regenerates site_v5/assets/css/v5-theme.css from sub.css)
"""Generate site_v5/assets/css/v5-theme.css: re-maps the V4 sub-page colours (ivory ground, graphite ink, white cards,
graphite hairlines) onto the duPont REGISTRY surface roles for dark and light themes. Scoped to body.sub-page."""
import re

src = open('site_v5/assets/css/sub.css', encoding='utf-8').read()
src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)

def parse(s):
    """yield (prelude, body) where body is a str (declarations) or a list (nested rules)"""
    out, i, n = [], 0, len(s)
    while i < n:
        j = s.find('{', i)
        if j < 0: break
        pre = s[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            if s[k] == '{': depth += 1
            elif s[k] == '}': depth -= 1
            k += 1
        body = s[j + 1:k - 1]
        if pre.startswith('@media') or pre.startswith('@container') or pre.startswith('@supports'):
            out.append((pre, parse(body)))
        elif not pre.startswith('@'):
            out.append((pre, body))
        i = k
    return out

KEEP_WHITE = ('room-b', 'video', 'save', 'lbox', 'vbox', 'pinfo', 'calc-alt', 'vdp__panel', 'vdp__mb', 'tile__go', 'vdp__vid')
DARK_COMP = ('tile__a', 'vdp__panel', 'calc-out', 'tile--end', 'vdp__room-b')

def mix(a):
    return 'color-mix(in srgb, var(--on) %s%%, transparent)' % (round(float(a) * 100, 1))

def tx_decl(sel, prop, val):
    if 'scrim' in sel: return None
    v = val
    imp = '!important' in v
    if 'rgb(48 49 55' in v:
        v = re.sub(r'rgb\(48 49 55 / (\.?\d*\.?\d+)\)', lambda m: mix(m.group(1)), v)
    if prop.startswith('background') or prop in ('border-color',):
        if re.search(r'#fff\b|#ffffff\b', v) and not any(k in sel for k in KEEP_WHITE):
            v = re.sub(r'#fff\b|#ffffff\b', 'var(--card)', v)
        if 'var(--graphite)' in v and prop.startswith('background'):
            if any(k in sel for k in ('aria-pressed', 'aria-checked', 'is-cur', 'is-on', ':hover', ':focus-visible')):
                v = v.replace('var(--graphite)', 'var(--on)')
            else:
                v = v.replace('var(--graphite)', 'var(--dk)')
        if 'rgb(240 238 233' in v:
            v = re.sub(r'rgb\(240 238 233 / (\.?\d*\.?\d+)\)', lambda m: 'color-mix(in srgb, var(--s0) %s%%, transparent)' % round(float(m.group(1)) * 100), v)
    if v == val: return None
    return '%s: %s' % (prop, v if imp or not '!important' in val else v)

def emit(rules, ind=''):
    out = []
    for pre, body in rules:
        if isinstance(body, list):
            inner = emit(body, ind + '  ')
            if inner: out.append('%s%s {\n%s\n%s}' % (ind, pre, '\n'.join(inner), ind))
            continue
        decls = []
        pressed_inverse = False
        for d in body.split(';'):
            if ':' not in d: continue
            prop, val = d.split(':', 1); prop = prop.strip(); val = val.strip()
            if not prop or prop.startswith('--'): continue
            r = tx_decl(pre, prop, val)
            if r:
                decls.append(r)
                if 'var(--on)' in r and prop.startswith('background') and 'var(--graphite)' in val: pressed_inverse = True
        if pressed_inverse: decls.append('color: var(--s0)')
        # a white fill that stays white (hover of outlined pills on dark cards) needs dark ink, not the swapped graphite
        if re.search(r'background(-color)?:\s*#fff', body) and re.search(r'(^|;)\s*color:\s*var\(--graphite\)', body) and any(k in pre for k in KEEP_WHITE):
            decls.append('color: #0D0D0D')
        # V4 greys hard-coded for an ivory ground
        if re.search(r'(^|;)\s*color:\s*#4a4b50', body): decls.append('color: var(--on-v)')
        if decls:
            sels = ', '.join('body.sub-page main ' + x.strip() for x in pre.split(','))
            out.append('%s%s { %s; }' % (ind, sels, '; '.join(decls)))
    return out

lines = emit(parse(src))
HEAD = """/* GENERATED by theme_gen.py from sub.css (2026-11-05) — the V4 sub-page colours re-mapped onto the duPont REGISTRY
   surface roles. Do not edit by hand; edit sub.css / the generator and re-run. */
body.sub-page { background: var(--s0); color: var(--on); }
/* the token swap stays inside <main>: the shared showrooms footer block keeps its own (dark) V4 colours */
body.sub-page main { --graphite: var(--on); --pewter: var(--on-v); --hair-ivory: color-mix(in srgb, var(--on) 14%, transparent);
  --card: var(--s2); --pop: var(--s3); color: var(--on); }
body.sub-page .inq__sheet { background: var(--card); }
body.sub-page .inv__menu li.is-active { background: color-mix(in srgb, var(--on) 8%, transparent); }
body.sub-page .inv__ico circle { fill: var(--card); }
body.sub-page .vdp__calc .inq__f input, body.sub-page .vdp__calc .inq__f select { background-color: var(--s1); }
:root, :root[data-theme="dark"] { --dk: color-mix(in srgb, #C6C6C6 12%, #0D0D0D); --dk-hi: color-mix(in srgb, #C6C6C6 17%, #0D0D0D); }
:root[data-theme="light"] { --dk: color-mix(in srgb, #C6C6C6 12%, #0D0D0D); --dk-hi: color-mix(in srgb, #C6C6C6 17%, #0D0D0D); }
"""
open('site_v5/assets/css/v5-theme.css', 'w', encoding='utf-8').write(HEAD + '\n'.join(lines) + '\n')
print(len(lines), 'rules')

